from __future__ import annotations

import html
import os
import re
from pathlib import Path

import markdown
from markdown.extensions.codehilite import CodeHiliteExtension
from markdown.extensions.tables import TableExtension
from markdown.extensions.toc import TocExtension
from markdown.extensions.fenced_code import FencedCodeExtension
from markdown.extensions.nl2br import Nl2BrExtension
from markdown.extensions.sane_lists import SaneListExtension
from markdown.extensions.attr_list import AttrListExtension

from .styles import get_full_css

# ── PROMTOBIA attribution constant ─────────────────────────────────────────────
PROMTOBIA_CREDIT = "Task done for PROMTOBIA"
PROMTOBIA_EMOJI  = "⚡"


# ── Helper: extract first h1 from markdown text ────────────────────────────────
def _extract_title(md_text: str, fallback: str = "Document") -> str:
    """Extract the first ATX or setext H1 heading from markdown text as a plain-text title."""
    # ATX heading: # Title
    m = re.search(r"^#\s+(.+)$", md_text, re.MULTILINE)
    if m:
        # Strip any trailing # and inline markup
        return re.sub(r"[*_`~\[\]#]", "", m.group(1)).strip()
    # Setext heading underlined with ===
    m = re.search(r"^(.+)\n={3,}\s*$", md_text, re.MULTILINE)
    if m:
        return m.group(1).strip()
    return fallback


# ── Build Markdown processor ───────────────────────────────────────────────────
def _build_md_processor() -> markdown.Markdown:
    """Return a configured Markdown processor with all desired extensions."""
    extensions = [
        FencedCodeExtension(),
        CodeHiliteExtension(linenums=False, guess_lang=True, css_class="highlight"),
        TableExtension(),
        TocExtension(permalink=True, toc_depth="2-4"),
        Nl2BrExtension(),
        SaneListExtension(),
        AttrListExtension(),
        "markdown.extensions.abbr",
        "markdown.extensions.footnotes",
        "markdown.extensions.meta",
        "markdown.extensions.smarty",
        "markdown.extensions.def_list",
        "markdown.extensions.admonition",
        "markdown.extensions.wikilinks",
    ]
    return markdown.Markdown(extensions=extensions, output_format="html")


# ── PROMTOBIA banner & footer ──────────────────────────────────────────────────
def _build_banner() -> str:
    return (
        f'<div class="promtobia-banner">'
        f'<span><span class="badge-icon">{PROMTOBIA_EMOJI}</span>'
        f"{PROMTOBIA_CREDIT}"
        f'<span class="badge-icon">{PROMTOBIA_EMOJI}</span></span>'
        f"</div>"
    )


def _build_footer() -> str:
    return (
        '<footer class="page-footer">'
        "Generated by <strong>md2html</strong> &mdash; "
        f'<span class="promtobia-credit">{PROMTOBIA_EMOJI} {PROMTOBIA_CREDIT}</span>'
        "</footer>"
    )


# ── Main public API ────────────────────────────────────────────────────────────

def convert_text(
    md_text: str,
    title: str | None = None,
    theme: str = "auto",
) -> str:
    """
    Convert a Markdown string to a complete, standalone HTML5 document.

    Parameters
    ----------
    md_text : str
        The Markdown source text.
    title : str, optional
        Custom HTML <title>. Defaults to the first H1 found in *md_text*.
    theme : str
        One of ``'light'``, ``'dark'``, or ``'auto'`` (default).

    Returns
    -------
    str
        A complete HTML5 document string.
    """
    if not isinstance(md_text, str):
        raise TypeError(f"md_text must be str, got {type(md_text).__name__}")

    md_text = md_text or ""

    # Resolve title
    doc_title = title or _extract_title(md_text, fallback="Untitled Document")

    # Convert markdown → HTML fragment
    md_proc = _build_md_processor()
    body_html = md_proc.convert(md_text)

    # Build theme colour-scheme meta
    color_scheme_map = {"light": "light", "dark": "dark", "auto": "light dark"}
    color_scheme = color_scheme_map.get(theme, "light dark")

    css = get_full_css()
    banner = _build_banner()
    footer = _build_footer()
    safe_title = html.escape(doc_title)

    document = f"""<!DOCTYPE html>
<html lang="en" data-theme="{html.escape(theme)}">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <meta name="color-scheme" content="{color_scheme}" />
  <meta name="generator" content="md2html — {PROMTOBIA_CREDIT}" />
  <title>{safe_title}</title>
  <style>
{css}
  </style>
</head>
<body>
{banner}
<header class="page-header">
  <div class="title-row">
    <h1 class="doc-title">{safe_title}</h1>
  </div>
</header>
<main>
{body_html}
</main>
{footer}
</body>
</html>"""

    return document


def convert_file(
    input_path: str | os.PathLike,
    output_path: str | os.PathLike | None = None,
    title: str | None = None,
    theme: str = "auto",
) -> Path:
    """
    Read a Markdown file, convert it to HTML, and write the result.

    Parameters
    ----------
    input_path : str or Path
        Path to the source ``.md`` file.
    output_path : str or Path, optional
        Destination ``.html`` file path. Defaults to the same directory as
        *input_path* with a ``.html`` extension.
    title : str, optional
        Custom document title.
    theme : str
        ``'light'``, ``'dark'``, or ``'auto'``.

    Returns
    -------
    Path
        The resolved path of the written HTML file.
    """
    input_path = Path(input_path)
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")
    if not input_path.is_file():
        raise ValueError(f"Input path is not a file: {input_path}")

    md_text = input_path.read_text(encoding="utf-8")
    resolved_title = title or _extract_title(md_text, fallback=input_path.stem)

    html_doc = convert_text(md_text, title=resolved_title, theme=theme)

    if output_path is None:
        output_path = input_path.with_suffix(".html")
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(html_doc, encoding="utf-8")

    return output_path


def convert_directory(
    input_dir: str | os.PathLike,
    output_dir: str | os.PathLike | None = None,
    theme: str = "auto",
    recursive: bool = False,
) -> list[Path]:
    """
    Convert all ``.md`` files in a directory (optionally recursive).

    Parameters
    ----------
    input_dir : str or Path
        Source directory containing ``.md`` files.
    output_dir : str or Path, optional
        Destination directory. Defaults to same as *input_dir*.
    theme : str
        ``'light'``, ``'dark'``, or ``'auto'``.
    recursive : bool
        If True, also process subdirectories.

    Returns
    -------
    list[Path]
        List of paths for each generated HTML file.
    """
    input_dir = Path(input_dir)
    if not input_dir.is_dir():
        raise NotADirectoryError(f"Not a directory: {input_dir}")

    output_dir = Path(output_dir) if output_dir else input_dir
    glob_pattern = "**/*.md" if recursive else "*.md"
    md_files = sorted(input_dir.glob(glob_pattern))

    if not md_files:
        return []

    results: list[Path] = []
    for md_file in md_files:
        # Preserve relative sub-path when recursive
        rel = md_file.relative_to(input_dir)
        out_file = (output_dir / rel).with_suffix(".html")
        results.append(convert_file(md_file, out_file, theme=theme))

    return results
